// Traceability generator and verifier: REQ-* → module → T-* test, and F5 code → N-<CODE> case; writes TRACEABILITY.md.
// Exits non-zero if a REQ lacks a test or a module, if a module cites no REQ or DP, or if a code has no case and is not declared unreachable (Part 6, DoD 2).
package main

import (
	"bufio"
	"fmt"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
)

// modules are the production package roots of the vhub PoC.
var modules = []string{"internal/core", "internal/server", "internal/client", "internal/clock", "internal/telemetry", "cmd/alexandria-server", "cmd/alexandria-client", "deploy/fake-idp", "deploy/fake-connector"}

// Patterns of requirement, decision, test and code references.
var (
	reqRe   = regexp.MustCompile(`REQ-(SYS|HUB|CLI|DOC)-[0-9]{3}`)
	dpRe    = regexp.MustCompile(`DP-[0-9]+`)
	testRe  = regexp.MustCompile(`func (TestT_(SYS|HUB|CLI|DOC)_((?:[0-9]{3}_?)+)[A-Za-z0-9_]*)\(`)
	constRe = regexp.MustCompile(`(?m)^\t([A-Za-z]+)\s+Code\s+= "([A-Z0-9_]+)"$`)
	caseRe  = regexp.MustCompile(`(?m)^\tcodes\.([A-Za-z]+):`)
)

// requirement is one row of spec/requirements.tsv.
type requirement struct{ id, section, summary string }

// readRequirements loads the 81 requirements.
func readRequirements() ([]requirement, error) {
	f, err := os.Open("spec/requirements.tsv")
	if err != nil {
		return nil, err
	}
	defer func() { _ = f.Close() }()
	var out []requirement
	s := bufio.NewScanner(f)
	for s.Scan() {
		if line := s.Text(); line != "" && !strings.HasPrefix(line, "#") {
			p := strings.SplitN(line, "\t", 3)
			out = append(out, requirement{p[0], p[1], p[2]})
		}
	}
	return out, s.Err()
}

// walk calls fn for every Go file under the repository roots, skipping vendored and generated folders.
func walk(roots []string, fn func(path string, src []byte)) {
	for _, r := range roots {
		_ = filepath.WalkDir(r, func(p string, d os.DirEntry, err error) error {
			if err != nil || d.IsDir() || !strings.HasSuffix(p, ".go") {
				return nil
			}
			b, err := os.ReadFile(p) // #nosec G304 G122 -- repository files.
			if err == nil {
				fn(p, b)
			}
			return nil
		})
	}
}

// header returns the comment lines before the package clause.
func header(path string) string {
	f, err := parser.ParseFile(token.NewFileSet(), path, nil, parser.PackageClauseOnly|parser.ParseComments)
	if err != nil || f.Doc == nil {
		return ""
	}
	return f.Doc.Text()
}

// testsByReq maps each REQ to the T-* tests that realise it.
func testsByReq() map[string][]string {
	out := map[string][]string{}
	walk([]string{"internal", "conformance", "cmd", "deploy"}, func(p string, src []byte) {
		if !strings.HasSuffix(p, "_test.go") {
			return
		}
		for _, m := range testRe.FindAllStringSubmatch(string(src), -1) {
			for _, n := range strings.Split(strings.Trim(m[3], "_"), "_") {
				id := "REQ-" + m[2] + "-" + n
				out[id] = append(out[id], m[1]+" ("+p+")")
			}
		}
	})
	return out
}

// modulesByReq maps each REQ to the packages whose headers cite it, and lists packages citing neither a REQ nor a DP.
func modulesByReq() (map[string][]string, []string) {
	cites := map[string]map[string]bool{}
	other := map[string]bool{}
	walk(modules, func(p string, _ []byte) {
		if strings.HasSuffix(p, "_test.go") {
			return
		}
		dir := filepath.ToSlash(filepath.Dir(p))
		h := header(p)
		if cites[dir] == nil {
			cites[dir] = map[string]bool{}
		}
		for _, r := range reqRe.FindAllString(h, -1) {
			cites[dir][r] = true
		}
		if dpRe.MatchString(h) {
			other[dir] = true
		}
	})
	out := map[string][]string{}
	var orphans []string
	for dir, rs := range cites {
		if len(rs) == 0 && !other[dir] {
			orphans = append(orphans, dir)
		}
		for r := range rs {
			out[r] = append(out[r], dir)
		}
	}
	for r := range out {
		sort.Strings(out[r])
	}
	sort.Strings(orphans)
	return out, orphans
}

// codeCoverage returns every catalog code with whether a negative case exists.
func codeCoverage() ([]string, map[string]bool, error) {
	src, err := os.ReadFile("internal/core/codes/codes.go")
	if err != nil {
		return nil, nil, err
	}
	byConst := map[string]string{}
	var all []string
	for _, m := range constRe.FindAllStringSubmatch(string(src), -1) {
		byConst[m[1]] = m[2]
		all = append(all, m[2])
	}
	covered := map[string]bool{}
	walk([]string{"conformance"}, func(p string, b []byte) {
		if strings.Contains(p, "negative") {
			for _, m := range caseRe.FindAllStringSubmatch(string(b), -1) {
				covered[byConst[m[1]]] = true
			}
		}
	})
	return all, covered, nil
}

// main writes TRACEABILITY.md and exits non-zero on any gap.
func main() {
	reqs, err := readRequirements()
	if err != nil {
		fail(err)
	}
	tests := testsByReq()
	mods, orphans := modulesByReq()
	all, covered, err := codeCoverage()
	if err != nil {
		fail(err)
	}
	oq, _ := os.ReadFile("OPEN_QUESTIONS.md")
	var b strings.Builder
	var problems []string
	withTest, withModule := 0, 0
	b.WriteString("# TRACEABILITY\n\nGenerated by `go run ./conformance/trace` (`make trace`). Do not edit by hand.\n\n")
	b.WriteString("## Requirements → modules → tests\n\n| Requirement | Section | Summary | Modules | Tests T-* |\n| --- | --- | --- | --- | --- |\n")
	for _, r := range reqs {
		t, m := tests[r.id], mods[r.id]
		if len(t) > 0 {
			withTest++
		} else {
			problems = append(problems, r.id+" has no T-* test")
		}
		if len(m) > 0 {
			withModule++
		} else {
			problems = append(problems, r.id+" has no module")
		}
		names := make([]string, 0, len(t))
		for _, x := range t {
			names = append(names, "`"+strings.SplitN(x, " ", 2)[0]+"`")
		}
		sort.Strings(names)
		fmt.Fprintf(&b, "| %s | %s | %s | %s | %s |\n", r.id, r.section, r.summary, "`"+strings.Join(m, "`, `")+"`", strings.Join(dedupe(names), ", "))
	}
	b.WriteString("\n## Catalog codes → negative cases N-<CODE>\n\n| Code | Case |\n| --- | --- |\n")
	reached := 0
	for _, c := range all {
		state := "`N-" + c + "` (conformance/negative_*_test.go)"
		switch {
		case covered[c]:
			reached++
		case strings.Contains(string(oq), c):
			state = "unreachable in the PoC, see OPEN_QUESTIONS.md"
		default:
			problems = append(problems, c+" has no negative case and is not declared unreachable")
			state = "**missing**"
		}
		fmt.Fprintf(&b, "| `%s` | %s |\n", c, state)
	}
	for _, o := range orphans {
		problems = append(problems, o+" cites neither a REQ-* nor a DP-*")
	}
	fmt.Fprintf(&b, "\n## Summary\n\n- Requirements with a test: %d / %d\n- Requirements with a module: %d / %d\n- Codes with a negative case: %d / %d\n- Modules without REQ or DP: %d\n",
		withTest, len(reqs), withModule, len(reqs), reached, len(all), len(orphans))
	if err := os.WriteFile("TRACEABILITY.md", []byte(b.String()), 0o600); err != nil {
		fail(err)
	}
	fmt.Printf("TRACEABILITY.md: %d/%d REQ with test, %d/%d with module, %d/%d codes with N-<CODE>\n", withTest, len(reqs), withModule, len(reqs), reached, len(all))
	if len(problems) > 0 {
		for _, p := range problems {
			fmt.Fprintln(os.Stderr, "trace:", p)
		}
		os.Exit(1)
	}
}

// dedupe removes adjacent duplicates of a sorted list.
func dedupe(s []string) []string {
	var out []string
	for i, x := range s {
		if i == 0 || x != s[i-1] {
			out = append(out, x)
		}
	}
	return out
}

// fail prints an error and exits.
func fail(err error) { fmt.Fprintln(os.Stderr, "trace:", err); os.Exit(1) }
